#!/bin/sh
# Build docs/ai/KLANG_FOR_AI.md by concatenating the AI guide parts.
# Deterministic: fixed order, fixed separators, no timestamps.
set -e
ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
AI="$ROOT/docs/ai"
OUT="$AI/KLANG_FOR_AI.md"
{
  printf '<!-- GENERATED by scripts/build_ai_guide.sh — do not edit directly. -->\n'
  for f in core.md pitfalls.md python-to-klang.md stdlib.md errors.md; do
    printf '\n<!-- ===== %s ===== -->\n' "$f"
    cat "$AI/$f"
  done
} > "$OUT"
echo "wrote $OUT"
